for (const width of [1440, 390]) test(`platform screens and access confirmation are accessible without page overflow at ${width}px`, async ({ page }) => {
  const state = await platformFixture(page)
  await page.setViewportSize({ width, height: width === 1440 ? 1000 : 900 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await open(page)
  await assertAccessible(page)
  if (width === 390) {
    await screenshot(page, 'overview-mobile')
    const menu = page.getByRole('button', { name: 'Open navigation' })
    await menu.click()
    const currentNavigation = page.getByRole('navigation', { name: 'Platform', exact: true }).getByRole('link', { name: 'Overview', exact: true })
    await expect(currentNavigation).toBeFocused()
    await currentNavigation.click()
    await expect(menu).toBeFocused()
    await expect(menu).toHaveAttribute('aria-expanded', 'false')
    await menu.click()
    await expect(currentNavigation).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(menu).toBeFocused()
    await expect(menu).toHaveAttribute('aria-expanded', 'false')
  }
  await company(page)
  await assertAccessible(page)
  if (width === 1440) await screenshot(page, 'company-desktop')
  await page.getByRole('button', { name: 'Suspend company', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await assertAccessible(page)
  if (width === 1440) await screenshot(page, 'access-dialog')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Suspend company', exact: true })).toBeFocused()
  await open(page, 'platform-companies')
  await assertAccessible(page)
  if (width === 1440) await screenshot(page, 'companies-desktop')
  await open(page, 'platform-audit')
  await assertAccessible(page)
  if (width === 1440) {
    await screenshot(page, 'audit-desktop')
    for (const additionalWidth of [320, 768, 1024]) {
      await page.setViewportSize({ width: additionalWidth, height: 900 })
      for (const route of ['platform-overview', 'platform-companies', `platform-company?id=${ids.northstar}`, 'platform-audit']) {
        await open(page, route)
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `${route} must fit ${additionalWidth}px`).toBe(true)
      }
    }
  }
  expect(state.errors).toEqual([])
})
