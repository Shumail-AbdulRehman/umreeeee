import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { platformFixture, ids } from './fixtures/platform-api.js'

const captures = new URL('../../docs/planning/platform-owner/screenshots/', import.meta.url)

async function screenshot(page, name) {
  await mkdir(captures, { recursive: true })
  await page.screenshot({ path: fileURLToPath(new URL(`${name}.png`, captures)), fullPage: true, animations: 'disabled' })
}

async function open(page, hash = 'platform-overview') {
  await page.goto(`/#${hash}`)
  await expect(page.locator('.platform-workspace > .shell')).toBeVisible()
  await expect(page.locator('.platform-loading')).toHaveCount(0)
}

async function company(page, companyId = ids.northstar) {
  await open(page, `platform-company?id=${companyId}`)
  await expect(page.getByRole('heading', { level: 1, name: companyId === ids.evergreen ? 'Evergreen Data' : 'Northstar Labs' })).toBeVisible()
}

async function assertAccessible(page) {
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(result.violations).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
}

function platformRequests(state, suffix) {
  return state.requests.filter((request) => request.path === `/api/platform/${suffix}`)
}

