test('access actions require a reason, change one company once, restore focus and appear in history', async ({ page }) => {
  const state = await platformFixture(page)
  await company(page)
  const opener = page.getByRole('button', { name: 'Suspend company', exact: true })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: 'Suspend Northstar Labs?' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Suspend company' })).toBeDisabled()
  await dialog.getByLabel('Reason', { exact: true }).fill('   ')
  await expect(dialog.getByRole('button', { name: 'Suspend company' })).toBeDisabled()
  await dialog.getByLabel('Reason', { exact: true }).fill('Temporary pause requested by the company')
  await screenshot(page, 'access-dialog')
  await assertAccessible(page)
  await dialog.getByRole('button', { name: 'Suspend company' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Reactivate company', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Reactivate company', exact: true })).toBeFocused()
  await expect(page.locator('.company-heading .badge')).toHaveText('Suspended')
  await expect(page.getByRole('region', { name: 'Audit events' })).toContainText('Temporary pause requested by the company')
  expect(state.statusChanges).toEqual([{ company_id: ids.northstar, status: 'suspended', version: 1, reason: 'Temporary pause requested by the company' }])
  await page.getByRole('button', { name: 'Reactivate company', exact: true }).click()
  const reactivate = page.getByRole('dialog', { name: 'Reactivate Northstar Labs?' })
  await reactivate.getByLabel('Reason', { exact: true }).fill('Company confirmed access can resume')
  await reactivate.getByRole('button', { name: 'Reactivate company' }).click()
  await expect(page.locator('.company-heading .badge')).toHaveText('Active')
  expect(state.statusChanges.at(-1)).toMatchObject({ status: 'active', version: 2 })
  expect(state.errors).toEqual([])
})

